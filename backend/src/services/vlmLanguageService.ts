// ── LibreTranslate-backed translation ────────────────────────────────────
import { translationService } from './translationService';
import { logger } from '../utils/logger';

export interface ReportContent {
  technique: string;
  findings: string;
  impression: string;
  recommendation: string;
}

/**
 * Translates VLM report content to the target language using LibreTranslate.
 * Falls back to original content on any error.
 */
export async function translateReportContent(
  content: ReportContent,
  targetLang: string,
  sourceLang: string = 'en',
): Promise<ReportContent> {
  if (targetLang === sourceLang || !targetLang || targetLang === 'en') return content;

  const lang = (targetLang as SupportedLanguage) in SUPPORTED_LANGUAGES ? targetLang : 'en';
  if (lang === 'en') return content;

  const translated: ReportContent = { ...content };

  for (const field of ['technique', 'findings', 'impression', 'recommendation'] as const) {
    if (!content[field]) continue;
    try {
      const result = await translationService.translateText(content[field], sourceLang, lang);
      translated[field] = result.translatedText;
    } catch (err) {
      logger.warn(`[vlmLanguageService] translateReportContent.${field} failed: ${err}`);
    }
  }

  return translated;
}

// ── Public API ───────────────────────────────────────────────────────────

/**
 * Returns the UI labels for a given language code.
 * Falls back to English if the language is not supported.
 */
export function getReportLabels(language: string): ReportLabels {
  return LABELS[(language as SupportedLanguage)] ?? LABELS['en'];
}

/**
 * Translates an urgency level string into the target language.
 */
export function translateUrgency(urgency: string, language: string): string {
  const lang = (language as SupportedLanguage) in URGENCY_TRANSLATIONS ? (language as SupportedLanguage) : 'en';
  return URGENCY_TRANSLATIONS[lang][urgency?.toUpperCase()] ?? urgency;
}

/**
 * Builds a structured VLM system prompt that instructs the AI model
 * to produce its clinical impression in the requested language.
 * Used by the Python VLM microservice.
 */
export function buildVLMSystemPrompt(language: SupportedLanguage = 'en'): string {
  const meta = SUPPORTED_LANGUAGES[language] ?? SUPPORTED_LANGUAGES['en'];
  const labels = getReportLabels(language);

  if (language === 'en') {
    return [
      `You are a senior clinical radiologist. Generate a structured diagnostic report in English.`,
      `Structure your response strictly as JSON with these keys:`,
      `  technique, findings, impression, recommendation`,
      `Be concise, clinical, and evidence-based.`,
    ].join('\n');
  }

  return [
    `You are a senior clinical radiologist. Generate a structured diagnostic report in ${meta.englishName} (${meta.nativeName}).`,
    `You MUST write the entire report body in ${meta.englishName}. Do not mix languages.`,
    `Structure your response strictly as JSON with these keys (use these exact English keys):`,
    `  technique, findings, impression, recommendation`,
    `The VALUES of each key must be in ${meta.englishName}.`,
    `Section labels when rendered:`,
    `  technique      → "${labels.technique}"`,
    `  findings       → "${labels.findings}"`,
    `  impression     → "${labels.impression}"`,
    `  recommendation → "${labels.recommendation}"`,
    `Be concise, clinical, and evidence-based. Use medical terminology appropriate for ${meta.englishName}-speaking clinicians.`,
    `${meta.rtl ? 'Write right-to-left text correctly.' : ''}`,
  ].join('\n');
}

/**
 * Returns the human-readable list of supported languages for display in the frontend.
 */
export function listSupportedLanguages(): LanguageMeta[] {
  return Object.values(SUPPORTED_LANGUAGES);
}
