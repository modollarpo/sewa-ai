#!/usr/bin/env bash
# SEWA AI — scripts/generate-env-gcp.sh
# Reads Terraform GCP outputs and generates backend/.env.gcp
# Run after: cd infrastructure/terraform-gcp && terraform apply

set -euo pipefail

GREEN='\033[0;32m'; CYAN='\033[0;36m'; NC='\033[0m'
info()    { echo -e "${CYAN}[SEWA]${NC} $*"; }
success() { echo -e "${GREEN}[SEWA ✓]${NC} $*"; }

TF_DIR="infrastructure/terraform-gcp"
OUT="backend/.env.gcp"

[[ -d "$TF_DIR" ]] || { echo "Run from project root"; exit 1; }

info "Reading Terraform GCP outputs…"
cd "$TF_DIR"

GCP_PROJECT=$(terraform output -raw project_id 2>/dev/null || echo "")
DB_IP=$(terraform output -raw db_private_ip 2>/dev/null || echo "")
DB_PASS=$(terraform output -raw db_password 2>/dev/null || echo "")
REDIS_HOST=$(terraform output -raw redis_host 2>/dev/null || echo "")
REGISTRY=$(terraform output -raw artifact_registry 2>/dev/null || echo "europe-west2-docker.pkg.dev/${GCP_PROJECT}/sewa")

cd - >/dev/null

info "Writing ${OUT}…"
cat > "$OUT" << EOF
# SEWA AI — backend/.env.gcp (auto-generated $(date -u +"%Y-%m-%dT%H:%M:%SZ"))
# Generated by scripts/generate-env-gcp.sh

DEPLOY_TARGET=gcp
NODE_ENV=production
PORT=3000
REGION=eu
APP_URL=https://eu.sewaxai.health
CORS_ORIGINS=https://eu.sewaxai.health,https://app.sewaxai.health
LOG_LEVEL=info

DATABASE_URL=postgresql://sewa:${DB_PASS}@${DB_IP}:5432/sewa_ai?sslmode=require

REDIS_URL=redis://:$(gcloud redis instances describe sewa-ai-redis --region europe-west2 --project "${GCP_PROJECT}" --format='get(authString)' 2>/dev/null || echo "CHANGE_ME")@${REDIS_HOST}:6379/0

JWT_SECRET=$(openssl rand -base64 48)
JWT_REFRESH_SECRET=$(openssl rand -base64 48)
ENCRYPTION_KEY=$(openssl rand -hex 16)

AI_SERVICE_URL=http://sewa-ai-triage:8000
VLM_SERVICE_URL=http://sewa-ai-vlm:8001
UNCERTAINTY_SERVICE_URL=http://sewa-ai-uncertainty:8002
METACOGNITION_SERVICE_URL=http://sewa-ai-metacognition:8003
FL_SERVICE_URL=http://sewa-ai-federated:8004
CL_SERVICE_URL=http://sewa-ai-continuous:8005

STORAGE_PROVIDER=gcp
GCP_PROJECT_ID=${GCP_PROJECT}
GCP_BUCKET_SCANS=${GCP_PROJECT}-sewa-scans-eu
GCP_BUCKET_REPORTS=${GCP_PROJECT}-sewa-reports-eu
GCP_BUCKET_GRADCAM=${GCP_PROJECT}-sewa-gradcam-eu

# ── Fill these manually ──────────────────────────────────────
STRIPE_SECRET_KEY=sk_live_CHANGE_ME
STRIPE_WEBHOOK_SECRET=whsec_CHANGE_ME
PAYSTACK_SECRET_KEY=sk_live_CHANGE_ME
FIREBASE_PROJECT_ID=CHANGE_ME
FIREBASE_PRIVATE_KEY=CHANGE_ME
FIREBASE_CLIENT_EMAIL=CHANGE_ME
TWILIO_ACCOUNT_SID=CHANGE_ME
TWILIO_AUTH_TOKEN=CHANGE_ME
TWILIO_WHATSAPP_NUMBER=+14155238886
SENDGRID_API_KEY=CHANGE_ME
EMAIL_FROM=info@sewaxai.health
SMTP_HOST=smtp.sendgrid.net
SMTP_PORT=587
SMTP_USER=apikey
SMTP_PASS=\${SENDGRID_API_KEY}
DAILY_API_KEY=CHANGE_ME
EOF

success "Generated ${OUT}"
info "Next: cp backend/.env.gcp backend/.env && bash scripts/deploy.sh gcp"
